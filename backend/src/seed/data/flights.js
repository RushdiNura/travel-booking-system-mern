// Helper to build a departure/arrival pair from a base date + hour offsets.
const at = (daysFromNow, hour, minute = 0) => {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + daysFromNow);
  d.setUTCHours(hour, minute, 0, 0);
  return d;
};

